let assets = "ios/App/App/Assets.xcassets"
try png(#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 199 199">\#(tile(radius: 0))</svg>"#, size: 1024, opaque: true, to: "\(assets)/AppIcon.appiconset/AppIcon-512@2x.png")

// The launch storyboard aspect-fills this square, so the tile lands ~110 pt wide on a phone.
func launch(_ background: String) -> String {
  let side = 2732.0, t = 330.0
  return #"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \#(side) \#(side)"><rect width="\#(side)" height="\#(side)" fill="\#(background)"/><g transform="translate(\#((side - t) / 2) \#((side - t) / 2)) scale(\#(t / 199))">\#(tile(radius: 24))</g></svg>"#
}
let splash = "\(assets)/Splash.imageset"
for f in ["splash-2732x2732.png", "splash-2732x2732-1.png", "splash-2732x2732-2.png"] { remove("\(splash)/\(f)") }
try png(launch(canvas.light), size: 2732, opaque: true, to: "\(splash)/splash.png")
try png(launch(canvas.dark), size: 2732, opaque: true, to: "\(splash)/splash-dark.png")
try write(#"""
{
  "images" : [
    { "idiom" : "universal", "filename" : "splash.png" },
    { "idiom" : "universal", "filename" : "splash-dark.png", "appearances" : [ { "appearance" : "luminosity", "value" : "dark" } ] }
  ],
  "info" : { "version" : 1, "author" : "xcode" }
}
"""#, to: "\(splash)/Contents.json")

