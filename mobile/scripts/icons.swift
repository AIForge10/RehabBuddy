let res = "android/app/src/main/res"

/// The leg as vector paths, centered in a `box`-dp viewport at `height` dp tall.
func legVector(box: Double, height: Double, color: String) -> String {
  let s = height / legH
  return #"""
      <group android:scaleX="\#(s)" android:scaleY="\#(s)" android:translateX="\#((box - legW * s) / 2)" android:translateY="\#((box - height) / 2)">
          <path android:fillColor="\#(color)" android:pathData="\#(leg)"/>
      </group>
  """#
}

// Adaptive icon: 108 dp canvas, of which a 72 dp circle-to-square shows; the leg
// keeps the favicon's proportion of that (149 / 199).
let adaptiveLeg = 72 * legH / 199
for (name, color) in [("ic_launcher_foreground", "#FFFFFF"), ("ic_launcher_monochrome", "#000000")] {
  try write(#"""
  <?xml version="1.0" encoding="utf-8"?>
  <!-- Generated by mobile/scripts/icons.swift -->
  <vector xmlns:android="http://schemas.android.com/apk/res/android"
      android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  \#(legVector(box: 108, height: adaptiveLeg, color: color))
  </vector>
  """#, to: "\(res)/drawable/\(name).xml")
}
for name in ["ic_launcher", "ic_launcher_round"] {
  try write(#"""
  <?xml version="1.0" encoding="utf-8"?>
  <adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
      <background android:drawable="@color/ic_launcher_background"/>
      <foreground android:drawable="@drawable/ic_launcher_foreground"/>
      <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
  </adaptive-icon>
  """#, to: "\(res)/mipmap-anydpi-v26/\(name).xml")
}
try write(#"""
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">\#(teal)</color>
</resources>
"""#, to: "\(res)/values/ic_launcher_background.xml")
remove("\(res)/drawable-v24/ic_launcher_foreground.xml")
