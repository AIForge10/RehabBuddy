// Regenerates the app icons and launch screens from the brand mark: the white
// leg on brand teal, as in frontend/public/favicon.svg (the Figma export).
// macOS only, like iOS builds. Run from mobile/: `npm run icons`.
//
//   iOS      App Store icon (1024, opaque, square: iOS rounds the corners)
//            launch image, light and dark
//   Android  adaptive icon foreground + themed-icon monochrome (vectors)
//            legacy launcher PNGs for Android 7 (API 24-25)
//            launch screen (vector tile on the canvas color, light and dark)

import AppKit

let teal = "#4BAEA7"
let canvas = (light: "#F3F7F7", dark: "#070B0B") // --rb-canvas in frontend/src/index.css

let favicon = try String(contentsOfFile: "../frontend/public/favicon.svg", encoding: .utf8)
let leg = favicon.firstMatch(of: #/<path[^>]* d="([^"]+)"/#)!.1
// The leg is 91 × 149; the favicon centers it in a 199 tile at (55, 26).
let legW = 91.0, legH = 149.0

/// The 199 × 199 brand tile. `radius` 0 is full bleed; nil is a circle.
func tile(radius: Double?) -> String {
  let shape = radius.map { #"<rect width="199" height="199" rx="\#($0)" fill="\#(teal)"/>"# } ?? #"<circle cx="99.5" cy="99.5" r="99.5" fill="\#(teal)"/>"#
  // A circle crops more of the corners, so its leg is a little smaller.
  let legT = radius == nil ? "translate(99.5 99.5) scale(0.86) translate(-45.5 -74.5)" : "translate(55 26)"
  return #"\#(shape)<path transform="\#(legT)" fill="white" d="\#(leg)"/>"#
}

func png(_ svg: String, size: Int, opaque: Bool, to path: String) throws {
  guard let image = NSImage(data: Data(svg.utf8)) else { fatalError("could not render SVG for \(path)") }
  let ctx = CGContext(
    data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
    space: CGColorSpace(name: CGColorSpace.sRGB)!,
    bitmapInfo: (opaque ? CGImageAlphaInfo.noneSkipLast : CGImageAlphaInfo.premultipliedLast).rawValue)!
  NSGraphicsContext.current = NSGraphicsContext(cgContext: ctx, flipped: false)
  image.draw(in: NSRect(x: 0, y: 0, width: size, height: size))
  let data = NSBitmapImageRep(cgImage: ctx.makeImage()!).representation(using: .png, properties: [:])!
  try data.write(to: URL(fileURLWithPath: path))
}

func write(_ text: String, to path: String) throws {
  try FileManager.default.createDirectory(atPath: (path as NSString).deletingLastPathComponent, withIntermediateDirectories: true)
  try text.write(toFile: path, atomically: true, encoding: .utf8)
}

func remove(_ path: String) { try? FileManager.default.removeItem(atPath: path) }

